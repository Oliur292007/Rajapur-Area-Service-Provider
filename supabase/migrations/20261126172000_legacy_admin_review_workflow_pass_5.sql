-- Pass 5: admin review decision metadata and audit events
-- This migration does not approve, reject, import, or publish any legacy record.

alter table public.legacy_content_records
  add column if not exists review_decision text,
  add column if not exists reviewed_by uuid references auth.users(id) on delete set null,
  add column if not exists reviewed_at timestamptz,
  add column if not exists admin_review_notes text;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.legacy_content_records'::regclass
      and conname = 'legacy_content_records_review_decision_check'
  ) then
    alter table public.legacy_content_records
      add constraint legacy_content_records_review_decision_check
      check (review_decision is null or review_decision in ('approved','rejected','needs_clarification','duplicate'));
  end if;
end $$;

create table if not exists public.legacy_review_events (
  id bigint generated by default as identity primary key,
  legacy_record_id bigint references public.legacy_content_records(id) on delete restrict,
  review_task_id bigint references public.legacy_review_queue(id) on delete restrict,
  actor_id uuid references auth.users(id) on delete set null,
  action text not null check (action in (
    'record_approved','record_rejected','record_needs_clarification',
    'record_marked_duplicate','task_resolved','task_waived',
    'note_added','duplicate_linked'
  )),
  previous_state jsonb not null default '{}'::jsonb,
  new_state jsonb not null default '{}'::jsonb,
  note text,
  created_at timestamptz not null default now(),
  constraint legacy_review_events_target_check
    check (legacy_record_id is not null or review_task_id is not null)
);

create index if not exists idx_legacy_records_review_decision
  on public.legacy_content_records(review_decision, record_type);
create index if not exists idx_legacy_records_reviewed_at
  on public.legacy_content_records(reviewed_at desc);
create index if not exists idx_legacy_review_events_record
  on public.legacy_review_events(legacy_record_id, created_at desc);
create index if not exists idx_legacy_review_events_task
  on public.legacy_review_events(review_task_id, created_at desc);

alter table public.legacy_review_events enable row level security;
revoke all on public.legacy_review_events from anon, authenticated;
grant select on public.legacy_review_events to authenticated;
grant all on public.legacy_review_events to service_role;

drop policy if exists "Admins can read legacy review events" on public.legacy_review_events;
create policy "Admins can read legacy review events"
  on public.legacy_review_events
  for select
  to authenticated
  using ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');
